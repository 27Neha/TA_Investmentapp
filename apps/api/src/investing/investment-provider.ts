import { MandateEvent, SipEvent } from '../integrations/lifecycle/mandate';
import { PaymentEvent } from '../integrations/lifecycle/payment';

/**
 * Provider-independent boundary for payments, mandates and SIPs (Cybrilla / Fintech Primitives later).
 * NOTHING here is a Cybrilla endpoint: the real adapter does not exist until the documentation/sandbox is supplied.
 * The default binding fails closed. A fake exists ONLY under test/ and is never constructed by production code.
 */
export interface NormalizedProviderEvent {
  provider: string;
  /** Provider's own unique event id (webhook dedupe key). Never generated by us. */
  eventId: string;
  kind: 'PAYMENT' | 'MANDATE' | 'SIP';
  /** providerPaymentRef | providerMandateRef | providerSipRef */
  providerRef: string;
  paymentEvent?: PaymentEvent;
  mandateEvent?: MandateEvent;
  sipEvent?: SipEvent;
  /** Our own id echoed by the provider (e.g. SipPlan id for the first activation event). */
  localRef?: string;
  providerSipRef?: string;
  failureCode?: string;
  reason?: string;
  occurredAt: Date;
}

export class ProviderNotConfiguredError2 extends Error { readonly code = 'PROVIDER_NOT_CONFIGURED'; constructor(op: string) { super(`${op} is unavailable: the investment provider is not configured.`); } }
export class WebhookRejectedError extends Error { readonly code = 'WEBHOOK_REJECTED'; constructor(why: string) { super(`Webhook rejected: ${why}`); } }

export interface InvestmentProvider {
  readonly name: string;
  readonly environment: 'sandbox' | 'production' | 'none';
  isConnected(): boolean;
  createPayment(i: { paymentId: string; amount: string; schemeCode: string; idempotencyKey: string; method?: string }): Promise<{ providerPaymentRef: string; providerOrderRef?: string; redirectUrl?: string }>;
  /** Authenticated PULL of a payment's current status, used for reconciliation. null = provider has no record. */
  getPaymentStatus(providerPaymentRef: string): Promise<{ event: PaymentEvent; failureCode?: string; reason?: string; occurredAt: Date } | null>;
  createMandate(i: { mandateId: string; maxAmount: string; idempotencyKey: string }): Promise<{ providerMandateRef: string; authorizationUrl: string }>;
  cancelMandate(providerMandateRef: string): Promise<void>;
  /** Verify the provider's webhook authentication over the RAW request bytes, then normalise. Must throw WebhookRejectedError on any verification failure. */
  verifyAndNormalizeWebhook(raw: Buffer, headers: Record<string, string | string[] | undefined>): NormalizedProviderEvent[];
}

export const INVESTMENT_PROVIDER = Symbol('INVESTMENT_PROVIDER');

export class UnconfiguredInvestmentProvider implements InvestmentProvider {
  readonly name = 'none';
  readonly environment = 'none' as const;
  isConnected() { return false; }
  async createPayment(): Promise<never> { throw new ProviderNotConfiguredError2('Payment creation'); }
  async getPaymentStatus(): Promise<never> { throw new ProviderNotConfiguredError2('Payment status'); }
  async createMandate(): Promise<never> { throw new ProviderNotConfiguredError2('Mandate creation'); }
  async cancelMandate(): Promise<never> { throw new ProviderNotConfiguredError2('Mandate cancellation'); }
  verifyAndNormalizeWebhook(): never { throw new ProviderNotConfiguredError2('Webhook verification'); }
}
